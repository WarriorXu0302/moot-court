/**
 * 根据页面路径获取任务提示
 */
export function getTaskHint(pathname: string): TaskHintItem | null {
  // 从路径中提取页面标识，如 /student/case-detail → case-detail
  const match = pathname.match(/\/student\/([^/]+)/);
  if (match) {
    const key = match[1];
    return TASK_HINTS[key] || null;
  }
  return null;
}
