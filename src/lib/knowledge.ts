质证是指在法庭调查过程中，由诉讼当事人及其诉讼代理人对在法庭上出示的证据进行对质、核实，以确认其证据资格和证明力的诉讼活动。质证是法庭调查的核心环节，是证据认证的前提，也是当事人行使质证权的重要方式。

