- 第一阶段，证据的展示行为，即举证主体向法庭出示证据的行为。出示的方式大致有陈述发问、宣读、出示和播放。（1）书证：当庭宣读，忠实原意，不能更改变动。内容相对简短、扼要的书证比如居民身份证、驾驶证等，可以全文宣读；内容繁杂的比如医院的病历证明、伤害鉴定等，一般采用摘要宣读，将最具有证明力的段落和文句在法庭摘要宣读。如不宣读证词全文，要向法庭作简要说明，并宣读所需宣读的主要内容，使证据重点突出、简洁、有力，符合证据真实、合法的要求。（2）物证：以原物向法庭出示。不易保存的或大宗的物证采取照片或录像。（3）视听资料证据：必须实际播放。
