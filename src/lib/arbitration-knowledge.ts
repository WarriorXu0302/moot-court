export const ARB_JURISDICTION_KNOWLEDGE = `# 管辖权与仲裁协议效力（核心知识）
1. 仲裁协议独立性：仲裁条款与主合同在法律上相互独立，主合同的成立、变更、解除、无效或被撤销，不当然影响仲裁条款的效力
2. 管辖权异议：当事人对仲裁协议的存在、效力、范围提出异议的，由仲裁庭或仲裁机构依所适用的规则处理；仲裁庭可以先行就管辖权作出决定，也可以并入实体一并审理
3. 仲裁协议准据法的确定（涉外仲裁协议）——通行的三层逻辑：
   (1) 当事人明确约定了仲裁协议效力适用的法律的，适用该约定；
   (2) 未约定但约定了仲裁地的，适用仲裁地法律；
   (3) 既未约定法律也未约定仲裁地，或仲裁地约定不明的，适用法院地法律。
   关键点：合同中"解决合同争议适用的准据法"，不能直接当作仲裁条款效力的准据法，除非当事人对此作了明确的意思表示。
4. 仲裁协议要素：请求仲裁的意思表示、仲裁事项、选定的仲裁机构；要素欠缺是否导致无效，取决于所适用的法律与补充协议情况
5. 侵权等非合同性争议能否仲裁：取决于争议是否属于仲裁协议约定的事项范围，以及是否属于依法可仲裁的争议
6. 仲裁协议的相对性：仲裁协议原则上只约束协议当事人，第三人是否受约束须依法律规定或其同意判断`;

export const ARB_EVIDENCE_KNOWLEDGE = `# 仲裁中的举证与质证
1. 举证责任：主张权利或抗辩的一方就其主张的事实承担举证责任
2. 举证方式：提交书面证据（合同、函件、邮件、付款凭证等），说明证据来源与证明目的；外文证据通常需提交译文
3. 质证三性：真实性、合法性、关联性；质证意见须具体指向证据的哪一方面存在问题、依据是什么，不能只笼统表示"不认可"
4. 电子证据：关注来源可靠性、完整性、是否经公证或其他方式固定
5. 域外证据：关注形成地的公证认证或相关证明手续要求
6. 仲裁庭对证据的可采性与证明力享有较大裁量权，通常不严格适用诉讼证据规则`;

