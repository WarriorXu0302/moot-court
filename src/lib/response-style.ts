/**
 * 庭审页双模式回复设置：文本模式与语音模式采用完全不同的 AI 回复格式。
 *
 * - 文本模式：纯阅读体验，零 TTS 参与（不合成、不等待语音）；
 *   回复用 markdown 结构化（加粗/列表），便于屏幕阅读。
 * - 语音模式：回复将被分句实时转为语音播报；
 *   回复用自然口语、短句，禁止任何 markdown 符号（会被语音合成读出来或干扰分句）。
 */

/** 文本模式（阅读优化）格式指令 */
export const REPLY_FORMAT_TEXT = `

【输出形式：文字阅读模式】你的发言将以文字形式呈现在屏幕上供用户阅读（不会转为语音）：
- 可以使用 markdown 格式优化可读性：关键术语、法条名称、重要结论用 **加粗** 标记
- 分点论述时使用 1. 2. 3. 有序列表，层次清晰
- 保持庭审发言的口语语态，不要写成书面报告
- 以上格式要求只针对发言正文；LIFECYCLE 标签协议不受影响，按原样输出`;

/** 语音模式（播报优化）格式指令 */
export const REPLY_FORMAT_VOICE = `

【输出形式：语音播报模式】你的发言将被实时转为语音在法庭现场播放：
- 说自然口语，像真实庭审中说话一样连贯自然
- 句子简短明了，避免多层嵌套的长难句
- 禁止使用任何 markdown 符号（如 **、##、-、列表序号等），不要使用标题和分点格式，这些内容会被语音合成读出来
- 不要用括号描述神情、动作、语气
- 以上要求只针对发言正文；LIFECYCLE 标签协议不受影响，按原样输出`;

/** 按当前模式返回回复格式指令（拼接到发言 systemPrompt 末尾） */
export function replyFormatInstruction(voiceMode: boolean): string {
  return voiceMode ? REPLY_FORMAT_VOICE : REPLY_FORMAT_TEXT;
}
